package jpeg

// HuffCode represents a Huffman code and its bit length.
type HuffCode struct {
	Code   uint16
	Length uint8
}

// HuffmanTables contains precomputed Huffman tables for luminance and chrominance.
type HuffmanTables struct {
	// Standard tables for headers
	DCLumBits   [16]uint8
	DCLumVals   []uint8
	DCChromBits [16]uint8
	DCChromVals []uint8
	ACLumBits   [16]uint8
	ACLumVals   []uint8
	ACChromBits [16]uint8
	ACChromVals []uint8

	// Lookup tables for encoding
	DCLumCodes   [12]HuffCode
	DCChromCodes [12]HuffCode
	ACLumCodes   [256]HuffCode
	ACChromCodes [256]HuffCode
}

