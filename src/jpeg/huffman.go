// NewHuffmanTables creates standard JPEG Huffman tables.
func NewHuffmanTables() *HuffmanTables {
	ht := &HuffmanTables{
		DCLumBits:   stdDCLumBits,
		DCLumVals:   stdDCLumVals,
		DCChromBits: stdDCChromBits,
		DCChromVals: stdDCChromVals,
		ACLumBits:   stdACLumBits,
		ACLumVals:   stdACLumVals,
		ACChromBits: stdACChromBits,
		ACChromVals: stdACChromVals,
	}

	ht.DCLumCodes = buildCodeTable12(stdDCLumBits, stdDCLumVals)
	ht.DCChromCodes = buildCodeTable12(stdDCChromBits, stdDCChromVals)
	ht.ACLumCodes = buildCodeTable256(stdACLumBits, stdACLumVals)
	ht.ACChromCodes = buildCodeTable256(stdACChromBits, stdACChromVals)

	return ht
}

func buildCodeTable12(bits [16]uint8, vals []uint8) [12]HuffCode {
	var codes [12]HuffCode
	var code uint16
	valIdx := 0

	for length, count := range bits {
		for i := 0; i < int(count); i++ {
			if valIdx < len(vals) {
				symbol := vals[valIdx]
				if symbol < 12 {
					codes[symbol] = HuffCode{Code: code, Length: uint8(length + 1)}
				}
				valIdx++
			}
			code++
		}
		code <<= 1
	}
	return codes
}

func buildCodeTable256(bits [16]uint8, vals []uint8) [256]HuffCode {
	var codes [256]HuffCode
	var code uint16
	valIdx := 0

	for length, count := range bits {
		for i := 0; i < int(count); i++ {
			if valIdx < len(vals) {
				symbol := vals[valIdx]
				codes[symbol] = HuffCode{Code: code, Length: uint8(length + 1)}
				valIdx++
			}
			code++
		}
		code <<= 1
	}
	return codes
}

// EncodeDC returns the Huffman code for a DC category.
func (ht *HuffmanTables) EncodeDC(category uint8, isLuminance bool) (code uint16, length uint8) {
	var h HuffCode
	if isLuminance {
		h = ht.DCLumCodes[category]
	} else {
		h = ht.DCChromCodes[category]
	}
	return h.Code, h.Length
}

// EncodeAC returns the Huffman code for an AC (run, size) pair.
func (ht *HuffmanTables) EncodeAC(run, size uint8, isLuminance bool) (code uint16, length uint8) {
	rs := (run << 4) | size
	var h HuffCode
	if isLuminance {
		h = ht.ACLumCodes[rs]
	} else {
		h = ht.ACChromCodes[rs]
	}
	return h.Code, h.Length
}
